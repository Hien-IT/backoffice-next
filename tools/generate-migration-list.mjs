// Prints the migration versions bundled with Directus, filtered like directus/api/src/database/migrations/run.ts.
// usage: node tools/generate-migration-list.mjs > apps/api/src/database/migrations/directus-11.17.4.ts
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const MIGRATION_FILE = /^[0-9]+[A-Z]-[^.]+\.(?:js|ts)$/;

export function listVersions(dir) {
	return [
		...new Set(
			readdirSync(dir)
				.filter((f) => MIGRATION_FILE.test(f))
				.map((f) => f.split('-')[0]),
		),
	].sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const dir = fileURLToPath(new URL('../directus/api/src/database/migrations', import.meta.url));
	const versions = listVersions(dir);

	process.stdout.write(
		[
			'// Generated by tools/generate-migration-list.mjs from directus/api/src/database/migrations (do not edit).',
			`/** The ${versions.length} migration versions of Directus 11.17.4. */`,
			'export const DIRECTUS_MIGRATIONS: readonly string[] = [',
			...versions.map((v) => `\t'${v}',`),
			'];',
			'',
		].join('\n'),
	);
}
