// Copies the DR 11.17.4 theme data (directus/packages/themes/src/themes/**) into
// apps/web/src/theme/theme-presets.json for the system-theme and system-theme-overrides interfaces (spec FR-084,
// FR-085, D-89, research R6). The theme files are TypeScript, so the script runs under jiti (research "Kết quả kiểm
// T002, T003"): `nx run web:sync-themes`, or `jiti scripts/sync-theme-presets.mjs [out]`. The output is committed;
// src/theme/theme-presets.test.ts runs the script again into a temporary file and compares. Theme ids ("DR
// Default"...) are stored in directus_users and directus_settings, so they are copied as they are (check-brand.mjs
// skips this file).
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

export const SOURCE = 'directus/packages/themes/src/themes/**';
export const OUT = join(ROOT, 'apps/web/src/theme/theme-presets.json');
export const VERSION = '11.17.4';

/** The JSON text for `{ light, dark }` (the arrays of `@directus/themes`), with the source and the date on top. */
export function renderThemes({ light, dark }, date) {
	const pick = ({ id, name, appearance, rules }) => ({ id, name, appearance, rules });

	return (
		JSON.stringify(
			{
				$source: `${SOURCE} (Directus ${VERSION}), generated by apps/web/scripts/sync-theme-presets.mjs`,
				$generated: date,
				light: light.map(pick),
				dark: dark.map(pick),
			},
			null,
			'\t',
		) + '\n'
	);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	const themes = await import(join(ROOT, 'directus/packages/themes/src/themes/index.ts'));
	const out = resolve(process.argv[2] ?? OUT);
	writeFileSync(out, renderThemes(themes, new Date().toISOString().slice(0, 10)));
	process.stdout.write(`sync-theme-presets: wrote ${out}\n`);
}
