// Copies the Directus 11.17.4 app permission data into apps/web/src/permissions/app-permissions-data.json for the
// policy pages and the system-permissions matrix (spec 016 FR-055, FR-105, research R5):
// - `minimal`: appAccessMinimalPermissions of directus/packages/system-data/src/app-access-permissions/index.ts, built the
//   same way from its two yaml files (the defaults first, then the row);
// - `recommended`, `actions`, `disabledActions`: directus/app/src/app-permissions.ts (TypeScript, loaded with jiti).
// `nx run web:sync-permissions-data`, or `jiti scripts/sync-permissions-data.mjs [out]`. The output is committed;
// scripts/sync-permissions-data.test.ts renders it again and compares.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import yaml from 'js-yaml';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

const DATA = 'directus/packages/system-data/src/app-access-permissions';
export const SOURCES = [`${DATA}/schema-access-permissions.yaml`, `${DATA}/app-access-permissions.yaml`];
export const APP_PERMISSIONS = 'directus/app/src/app-permissions.ts';
export const OUT = join(ROOT, 'apps/web/src/permissions/app-permissions-data.json');
export const VERSION = '11.17.4';

// The `defaults` of app-access-permissions/index.ts.
const DEFAULTS = { policy: null, permissions: {}, validation: null, presets: null, fields: ['*'], system: true };

/** appAccessMinimalPermissions: the schema rows, then the app rows, each over the defaults. */
export function minimalPermissions(readText = (path) => readFileSync(join(ROOT, path), 'utf8')) {
	return SOURCES.flatMap((path) => yaml.load(readText(path))).map((row) => ({ ...DEFAULTS, ...row }));
}

/** The JSON text of the data file, with the sources and the date on top. */
export function renderPermissions(minimal, app, date) {
	return (
		JSON.stringify(
			{
				$source: `${SOURCES.join(', ')}, ${APP_PERMISSIONS} (Directus ${VERSION}), generated by apps/web/scripts/sync-permissions-data.mjs`,
				$generated: date,
				minimal,
				recommended: app.appRecommendedPermissions,
				actions: [...app.editablePermissionActions],
				disabledActions: app.disabledActions,
			},
			null,
			'\t',
		) + '\n'
	);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	const app = await import(join(ROOT, APP_PERMISSIONS));
	const out = resolve(process.argv[2] ?? OUT);
	writeFileSync(out, renderPermissions(minimalPermissions(), app, new Date().toISOString().slice(0, 10)));
	process.stdout.write(`sync-permissions-data: wrote ${out}\n`);
}
