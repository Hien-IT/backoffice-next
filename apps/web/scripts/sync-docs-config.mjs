// Backoffice (spec 033, FR-030..FR-033, research R8): writes apps/web/src/docs/configuration/supported.generated.json, the
// list of environment variables the API reads with the defaults it uses (DEFAULTS). The list is SUPPORTED_VARIABLES plus
// the variables with a default that the DR variable list does not name (TUS_*, RETENTION_*, PRESSURE_LIMITER_*...): the
// API reads those too, but they never needed an entry in SUPPORTED_VARIABLES, which only exists for the "unsupported
// variable" warning (see the comments in that file). The
// Configuration part of the documentation area shows the defaults from this file, so they cannot drift from the code;
// the descriptions are hand-written in docs/configuration/variables.ts and a test matches the two. Both sources are
// TypeScript, so the script runs under jiti: `pnpm --filter @backoffice/web sync-docs-config`, or
// `jiti scripts/sync-docs-config.mjs [out]`. The output is committed; scripts/sync-docs-config.test.ts runs the script
// again into a temporary file and compares.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

export const SOURCES = [
	'apps/api/src/config/supported-variables.ts',
	'libs/env/src/constants/defaults.ts',
	'libs/env/src/constants/directus-variables.ts',
];
export const OUT = join(ROOT, 'apps/web/src/docs/configuration/supported.generated.json');

// Defaults that depend on the machine (a path resolved from the working directory) are shown as the API documents them.
export const DISPLAY_DEFAULTS = { CONFIG_PATH: '.env' };

const text = (value) => {
	if (value === undefined || value === null) return undefined;
	if (Array.isArray(value)) return value.join(',');
	if (typeof value === 'object') return JSON.stringify(value);
	return String(value);
};

/** Names with a default that neither list matches: read by the API, never warned about (research R8, 2026-11-17). */
export function unlistedDefaults(patterns, defaults, listed) {
	const matches = (list, name) => list.some((regexp) => regexp.test(name));
	return Object.keys(defaults).filter((name) => !matches(patterns, name) && !matches(listed, name));
}

/**
 * The JSON text for the list of RegExp (`^NAME$` or `^PREFIX_.+$`), the defaults object and the DR variable list
 * (RegExp too).
 */
export function renderSupported(patterns, defaults, listed = []) {
	const extra = unlistedDefaults(patterns, defaults, listed).map((name) => new RegExp(`^${name}$`));

	const variables = [...patterns, ...extra].map((regexp) => {
		const pattern = regexp.source.replace(/^\^/, '').replace(/\$$/, '');
		const exact = /^[A-Z0-9_]+$/.test(pattern);
		const value = exact ? (DISPLAY_DEFAULTS[pattern] ?? text(defaults[pattern])) : undefined;

		return { pattern, exact, ...(value === undefined ? {} : { default: value }) };
	});

	return (
		JSON.stringify(
			{ $source: `${SOURCES.join(' + ')}, generated by apps/web/scripts/sync-docs-config.mjs`, variables },
			null,
			'\t',
		) + '\n'
	);
}

export async function loadSources() {
	const { SUPPORTED_VARIABLES } = await import(join(ROOT, SOURCES[0]));
	const { DEFAULTS } = await import(join(ROOT, SOURCES[1]));
	const { DIRECTUS_VARIABLES_REGEX } = await import(join(ROOT, SOURCES[2]));
	return { patterns: SUPPORTED_VARIABLES, defaults: DEFAULTS, listed: DIRECTUS_VARIABLES_REGEX };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	const { patterns, defaults, listed } = await loadSources();
	const out = resolve(process.argv[2] ?? OUT);
	const json = renderSupported(patterns, defaults, listed);
	writeFileSync(out, json);
	process.stdout.write(`sync-docs-config: wrote ${out} (${JSON.parse(json).variables.length} variables)\n`);
}
